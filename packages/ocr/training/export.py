"""Turns a trained DigitNet into the format `createDigitClassifier` in src/classify.ts reads.

Batch norm is folded into the convolutions, then weights are quantized to int8 with one scale per output channel.
`dequantized()` builds the float model the TypeScript code computes, so accuracy and the parity fixture are measured
on exactly what ships.

    uv run export.py <run>/final.pt     writes src/model/digits.ts and test/fixtures/digits-parity.json
"""

import argparse
import base64
import json
from pathlib import Path

import numpy as np
import torch
from torch import nn

from model import DigitNet

PACKAGE = Path(__file__).resolve().parent.parent


def b64(array: np.ndarray) -> str:
    return base64.b64encode(np.ascontiguousarray(array).tobytes()).decode("ascii")


def folded_layers(model: DigitNet) -> list[dict]:
    """Float layers with batch norm folded in: [{type, weight (out x ...), bias, relu}]."""
    model = model.eval()
    layers = []
    for block in model.blocks:
        conv, bn = block[0], block[1]
        std = torch.sqrt(bn.running_var + bn.eps)
        factor = bn.weight / std
        weight = conv.weight * factor[:, None, None, None]
        bias = bn.bias - bn.running_mean * factor
        layers.append({"type": "conv", "weight": weight.detach().numpy(), "bias": bias.detach().numpy()})
    linears = [m for m in model.head if isinstance(m, nn.Linear)]
    for i, linear in enumerate(linears):
        layers.append({
            "type": "dense",
            "weight": linear.weight.detach().numpy(),
            "bias": linear.bias.detach().numpy(),
            "relu": i < len(linears) - 1,
        })
    return layers


def quantize(weight: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    flat = weight.reshape(weight.shape[0], -1)
    scales = np.maximum(np.abs(flat).max(axis=1), 1e-12) / 127
    q = np.clip(np.round(flat / scales[:, None]), -127, 127).astype(np.int8)
    return q, scales.astype(np.float32)


def serialize(model: DigitNet, temperature: float) -> dict:
    out = []
    for layer in folded_layers(model):
        q, scales = quantize(layer["weight"])
        entry = {"type": layer["type"], "in": int(q.shape[1] // (9 if layer["type"] == "conv" else 1)), "out": int(q.shape[0])}
        if layer["type"] == "dense":
            entry["relu"] = layer["relu"]
        entry |= {"weights": b64(q), "scales": b64(scales), "bias": b64(layer["bias"].astype(np.float32))}
        out.append(entry)
    return {"size": 32, "temperature": round(float(temperature), 4), "layers": out}


def dequantized(serialized: dict) -> nn.Module:
    """The float network the TypeScript code runs for `serialized`."""

    class Net(nn.Module):
        def __init__(self):
            super().__init__()
            self.layers = []
            for layer in serialized["layers"]:
                q = np.frombuffer(base64.b64decode(layer["weights"]), dtype=np.int8).astype(np.float32)
                scales = np.frombuffer(base64.b64decode(layer["scales"]), dtype=np.float32)
                bias = torch.from_numpy(np.frombuffer(base64.b64decode(layer["bias"]), dtype=np.float32).copy())
                weight = torch.from_numpy((q.reshape(layer["out"], -1) * scales[:, None]).copy())
                if layer["type"] == "conv":
                    weight = weight.reshape(layer["out"], layer["in"], 3, 3)
                self.layers.append((layer, weight, bias))

        def forward(self, x):
            for layer, weight, bias in self.layers:
                if layer["type"] == "conv":
                    x = torch.max_pool2d(torch.relu(nn.functional.conv2d(x, weight, bias, padding=1)), 2)
                else:
                    x = nn.functional.linear(x.flatten(1), weight, bias)
                    if layer["relu"]:
                        x = torch.relu(x)
            return x

    return Net().eval()


def write_typescript(serialized: dict, path: Path) -> None:
    body = json.dumps(serialized, indent=2)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        "// Generated by packages/ocr/training/export.py from a model trained with train.py. Do not edit.\n"
        'import type { SerializedDigitModel } from "../classify.ts";\n\n'
        f"export const DIGIT_MODEL: SerializedDigitModel = {body};\n"
    )


def write_parity_fixture(serialized: dict, inputs: np.ndarray, path: Path) -> None:
    with torch.no_grad():
        logits = dequantized(serialized)(torch.from_numpy(inputs[:, None].astype(np.float32))).numpy()
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps({
        "inputs": [b64(x.astype(np.float32)) for x in inputs],
        "logits": logits.round(5).tolist(),
    }))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("checkpoint", type=Path, help="final.pt written by train.py --final")
    args = parser.parse_args()
    checkpoint = torch.load(args.checkpoint, weights_only=False)
    model = DigitNet(checkpoint["width"])
    model.load_state_dict(checkpoint["state"])
    serialized = serialize(model, checkpoint["temperature"])
    write_typescript(serialized, PACKAGE / "src" / "model" / "digits.ts")
    write_parity_fixture(serialized, checkpoint["parity_inputs"], PACKAGE / "test" / "fixtures" / "digits-parity.json")
    print(f"wrote src/model/digits.ts ({len(json.dumps(serialized)) // 1024} KB) and test/fixtures/digits-parity.json")


if __name__ == "__main__":
    main()
